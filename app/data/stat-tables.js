export var LEGENDARY_HP_BONUS_AT_LEVEL_60 = 80;
export var LEGENDARY_POWER_BONUS_AT_LEVEL_60 = 65;
export var LEGENDARY_STATS_BONUS_AT_LEVEL_60 = 65;

function bonusForLevel(table, level) {
  var numericLevel = Math.max(5, Math.min(60, Math.floor(Number(level) || 5)));
  return Number(table[numericLevel]) || 0;
}

export function shinyHpBonusForLevel(level) {
  return bonusForLevel(SHINY_HP_BONUS_BY_LEVEL, level);
}

export function shinyPowerBonusForLevel(level) {
  return bonusForLevel(SHINY_POWER_BONUS_BY_LEVEL, level);
}

export function shinyStatsBonusForLevel(level) {
  return bonusForLevel(SHINY_STATS_BONUS_BY_LEVEL, level);
}

export function evolutionHpBonusForLevel(level) {
  return bonusForLevel(EVOLUTION_HP_BONUS_BY_LEVEL, level);
}

export function evolutionPowerBonusForLevel(level) {
  return bonusForLevel(EVOLUTION_POWER_BONUS_BY_LEVEL, level);
}

export function evolutionStatsBonusForLevel(level) {
  return bonusForLevel(EVOLUTION_STATS_BONUS_BY_LEVEL, level);
}

function legendaryBonusForLevel(maxBonus, level) {
  var numericLevel = Math.max(1, Math.min(100, Math.floor(Number(level) || 1)));
  if (numericLevel >= 60) { return maxBonus; }
  return Math.round(maxBonus * numericLevel / 60);
}

export function legendaryHpBonusForLevel(level) {
  return legendaryBonusForLevel(LEGENDARY_HP_BONUS_AT_LEVEL_60, level);
}

export function legendaryPowerBonusForLevel(level) {
  return legendaryBonusForLevel(LEGENDARY_POWER_BONUS_AT_LEVEL_60, level);
}

export function legendaryStatsBonusForLevel(level) {
  return legendaryBonusForLevel(LEGENDARY_STATS_BONUS_AT_LEVEL_60, level);
}

export function isLegendaryPokemon(pokemon) {
  return Boolean(pokemon && (pokemon.rarityKey === "legendary" || pokemon.rarity === "legendary"));
}

export var STAT_CAP_LEVELS = Array.from({ length: 96 }, function (_, index) { return index + 5; });

function capForLevel(table, level, gainAfterSixty) {
  var numericLevel = Math.max(5, Math.min(100, Math.floor(Number(level) || 5)));
  return numericLevel <= 60 ? table[numericLevel] : table[60] + (numericLevel - 60) * gainAfterSixty;
}

export function maxHpForLevel(level) {
  return capForLevel(HP_CAPS, level, 3);
}

export function maxPowerForLevel(level) {
  return capForLevel(POWER_CAPS, level, 2);
}

export function maxStatsForLevel(level) {
  return capForLevel(STATS_CAPS, level, 2);
}

export function maxHpForPokemon(pokemon) {
  var level = pokemon && pokemon.level;
  return maxHpForLevel(level)
    + (pokemon && pokemon.isShiny ? shinyHpBonusForLevel(level) : 0)
    + (isLegendaryPokemon(pokemon) ? legendaryHpBonusForLevel(level) : 0);
}

export function maxPowerForPokemon(pokemon) {
  var level = pokemon && pokemon.level;
  return maxPowerForLevel(level)
    + (pokemon && pokemon.isShiny ? shinyPowerBonusForLevel(level) : 0)
    + (isLegendaryPokemon(pokemon) ? legendaryPowerBonusForLevel(level) : 0);
}

export function maxStatsForPokemon(pokemon) {
  var level = pokemon && pokemon.level;
  return maxStatsForLevel(level)
    + (pokemon && pokemon.isShiny ? shinyStatsBonusForLevel(level) : 0)
    + (isLegendaryPokemon(pokemon) ? legendaryStatsBonusForLevel(level) : 0);
}

export function clampToLimits(pokemon) {
  if (!pokemon) { return; }
  pokemon.maxHp = Math.min(pokemon.maxHp, maxHpForPokemon(pokemon));
  if (pokemon.moves && Array.isArray(pokemon.moves)) {
    var powerCap = maxPowerForPokemon(pokemon);
    var statsCap = maxStatsForPokemon(pokemon);
    pokemon.moves.forEach(function (move) {
      if (move) {
        if (typeof move.power === "number") { move.power = Math.min(move.power, powerCap); }
        if (typeof move.stats === "number") { move.stats = Math.min(move.stats, statsCap); }
      }
    });
  }
}

// Called only for an accepted evolution; the bonus never raises a cap.
export function applyEvolutionStatBonus(pokemon) {
  if (!pokemon) { return; }
  pokemon.maxHp += evolutionHpBonusForLevel(pokemon.level);
  (pokemon.moves || []).forEach(function (move) {
    if (!move) { return; }
    move.power = (Number(move.power) || 0) + evolutionPowerBonusForLevel(pokemon.level);
    move.stats = (Number(move.stats) || 0) + evolutionStatsBonusForLevel(pokemon.level);
  });
  clampToLimits(pokemon);
}
